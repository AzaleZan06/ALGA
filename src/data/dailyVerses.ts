/**
 * Returns a deterministic Daily Verse based on the date.
 * Every calendar date gets a specific verse from the pool.
 */
export function getDailyVerseForDate(date?: Date, offsetDays: number = 0): { verse: DailyVerse; formattedDate: string; isToday: boolean } {
  const targetDate = new Date(date || new Date());
  if (offsetDays !== 0) {
    targetDate.setDate(targetDate.getDate() + offsetDays);
  }

  // Calculate day-of-year or timestamp index
  const startOfYear = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const poolIndex = Math.abs(dayOfYear % DAILY_VERSES_POOL.length);
  const verse = DAILY_VERSES_POOL[poolIndex];

  // Formatted date string e.g. "Wednesday, Aug 5, 2026"
  const formattedDate = targetDate.toLocaleDateString('en-US', {
    weekday: 'long',
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  });

  const todayStr = new Date().toDateString();
  const isToday = targetDate.toDateString() === todayStr;

  return {
    verse: {
      ...verse,
      dateString: targetDate.toISOString().split('T')[0]
    },
    formattedDate,
    isToday
  };
}
